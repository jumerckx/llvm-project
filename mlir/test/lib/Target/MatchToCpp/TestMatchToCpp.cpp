::llvm::LogicalResult rewrite_rename(::mlir::PatternRewriter &rewriter,
                                     ::mlir::Operation *op) {
  OperationState state(op->getLoc(), "test.renamed");
  state.addOperands(op->getOperands());
  state.addTypes(op->getResultTypes());
  Operation *newOp = rewriter.create(state);
  rewriter.replaceOp(op, newOp->getResults());
  return success();
}

::llvm::LogicalResult rewrite_swap(::mlir::PatternRewriter &rewriter,
                                   ::mlir::Operation *op, ::mlir::Value a,
                                   ::mlir::Value b) {
  OperationState state(op->getLoc(), "test.swapped");
  state.addOperands({b, a});
  state.addTypes(op->getResultTypes());
  Operation *newOp = rewriter.create(state);
  rewriter.replaceOp(op, newOp->getResults());
  return success();
}

::llvm::LogicalResult rewrite_lower_addf(::mlir::PatternRewriter &rewriter,
                                         ::mlir::Operation *op, ::mlir::Value a,
                                         ::mlir::Value b) {
  OperationState state(op->getLoc(), "test.lowered_addf");
  state.addOperands({a, b});
  state.addTypes(op->getResultTypes());
  Operation *newOp = rewriter.create(state);
  rewriter.replaceOp(op, newOp->getResults());
  return success();
}

